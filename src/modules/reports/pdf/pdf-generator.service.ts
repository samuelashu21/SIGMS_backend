
import PDFDocument from 'pdfkit';
import type { Response } from 'express';

export const createPdfDocument = (
  response: Response,
  filename: string
) => {
  const document = new PDFDocument({
    size: 'A4',
    margins: {
      top: 45,
      bottom: 45,
      left: 45,
      right: 45
    },
    info: {
      Title: filename,
      Author: 'SIGMS',
      Creator: 'SIGMS Report Management'
    }
  });

  response.setHeader('Content-Type', 'application/pdf');
  response.setHeader(
    'Content-Disposition',
    `attachment; filename="${filename}"`
  );

  document.pipe(response);

  return document;
};

export const addPdfHeader = (
  document: PDFKit.PDFDocument,
  schoolName: string,
  title: string
) => {
  document
    .fontSize(18)
    .font('Helvetica-Bold')
    .text(schoolName, { align: 'center' });

  document
    .moveDown(0.4)
    .fontSize(14)
    .font('Helvetica-Bold')
    .text(title, { align: 'center' });

  document.moveDown(1);
};

export const addPdfFooter = (
  document: PDFKit.PDFDocument,
  generatedAt: Date
) => {
  const pageBottom = document.page.height - 35;

  document
    .fontSize(8)
    .font('Helvetica')
    .text(
      `Generated by SIGMS | ${generatedAt.toISOString()}`,
      45,
      pageBottom,
      {
        width: document.page.width - 90,
        align: 'center',
        lineBreak: false
      }
    );
};
